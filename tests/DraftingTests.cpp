#include <DXFCAD/Drafting.h>
#include <cmath>
#include <iostream>
#include <stdexcept>
using namespace DXFCAD;
void check(bool ok) { if (!ok) throw std::runtime_error("Drafting check failed"); }
template<typename F> void rejects(F f) { try { f(); } catch (const std::exception&) { return; } throw std::runtime_error("Invalid drafting accepted"); }
int main() {
    try {
        const auto line=createLine({0,0,2},{10,0,2});
        const auto cut=createLine({5,-5,2},{5,5,2});
        const auto beyond=createLine({15,-5,2},{15,5,2});
        const auto left=createLine({-5,-5,2},{-5,5,2});
        check(parseEntity(Drafting::trimLine(line,cut,false))->geometry().segments[0].end.x==5);
        check(parseEntity(Drafting::trimLine(line,cut,true))->geometry().segments[0].start.x==5);
        check(parseEntity(Drafting::trimLine(line,beyond,false,true))->geometry().segments[0].end.x==15);
        check(parseEntity(Drafting::trimLine(line,left,true,true))->geometry().segments[0].start.x==-5);
        rejects([&] { Drafting::trimLine(line,beyond,false); });
        rejects([&] { Drafting::trimLine(line,cut,false,true); });
        rejects([&] { Drafting::trimLine(line,beyond,true,true); });
        rejects([&] { Drafting::trimLine(line,createLine({5,1,2},{5,2,2}),false); });
        rejects([&] { Drafting::trimLine(line,createLine({0,2,2},{10,2,2}),false); });
        rejects([&] { Drafting::trimLine(line,createLine({5,-5,3},{5,5,3}),false); });
        const auto rich="0\nLINE\n5\nAB\n330\nAC\n10\n0\n20\n0\n30\n2\n11\n10\n21\n0\n31\n2\n102\n{APP\n11\n99\n102\n}\n1001\nApp\n1000\nopaque\n";
        const auto trimmed=parseEntity(Drafting::trimLine(rich,cut,false));
        check(trimmed->handle()=="AB" && trimmed->record().value(330)=="AC");
        check(trimmed->raw().find("102\n{APP\n11\n99\n102\n}")!=std::string::npos && trimmed->raw().find("1000\nopaque\n")!=std::string::npos);
        const auto offsetLine=parseEntity(Drafting::offset(line,3));
        check(offsetLine->geometry().segments[0].start.y==3 && offsetLine->geometry().segments[0].start.z==2);
        check(parseEntity(Drafting::offset(createCircle({1,2,3},5),-2))->geometry().circles[0].radius==3);
        const auto rectangle=createRectangle({0,0,2},{10,6,2});
        const auto inset=readLWPolyline(Drafting::offset(rectangle,1));
        check(inset.vertices()[0].x==1 && inset.vertices()[0].y==1 && inset.vertices()[2].x==9 && inset.vertices()[2].y==5);
        check(readLWPolyline(Drafting::offset(rectangle,-1)).vertices()[0].x==-1);
        rejects([&] { Drafting::offset(rectangle,4); });
        rejects([&] { Drafting::offset(rectangle,0); });
        rejects([&] { Drafting::offset(createCircle({0,0,0},1),-2); });
        rejects([&] { Drafting::offset(line,NAN); });
        const auto bulged=createLWPolyline(LWPolyline({{0,0,0.2},{10,0}},false));
        check(std::abs(readLWPolyline(Drafting::offset(bulged,1)).segments()[0].arc->radius-(readLWPolyline(bulged).segments()[0].arc->radius-1))<1e-9);
        const auto tilted=createLWPolyline(LWPolyline({{0,0},{10,0},{10,6},{0,6}},true,0,3,{1,2,3}));
        const auto tiltedOffset=readLWPolyline(Drafting::offset(tilted,1));
        check(tiltedOffset.elevation()==3 && tiltedOffset.extrusion().x==1 && tiltedOffset.vertices()[0].x==1);
        const auto arc="0\nARC\n10\n0\n20\n0\n40\n5\n50\n30\n51\n120\n";
        const auto arcOffset=parseEntity(Drafting::offset(arc,2));
        check(arcOffset->record().number(40)==7 && arcOffset->record().number(50)==30 && arcOffset->record().number(51)==120);
        const auto bowtie=createLWPolyline(LWPolyline({{0,0},{5,5},{0,5},{5,0}},true));
        rejects([&] { Drafting::offset(bowtie,1); });
        const auto elbow=createLWPolyline(LWPolyline({{0,0},{10,0},{10,10}},false));
        const auto rounded=readLWPolyline(Drafting::fillet(elbow,1,2));
        check(rounded.vertices().size()==4 && std::abs(rounded.vertices()[1].x-8)<1e-12 && std::abs(rounded.vertices()[2].y-2)<1e-12);
        check(std::abs(rounded.segments()[1].arc->radius-2)<1e-10);
        check(rounded.vertices()[1].bulge>0);
        const auto cw=createLWPolyline(LWPolyline({{0,0},{10,0},{10,-10}},false));
        check(readLWPolyline(Drafting::fillet(cw,1,2)).vertices()[1].bulge<0);
        rejects([&] { Drafting::fillet(elbow,0,2); });
        rejects([&] { Drafting::fillet(elbow,1,20); });
        rejects([&] { Drafting::fillet(elbow,1,0); });
        const auto wide="0\nLWPOLYLINE\n90\n3\n70\n0\n10\n0\n20\n0\n40\n2\n41\n4\n91\n10\n10\n10\n20\n0\n40\n6\n41\n8\n91\n11\n10\n10\n20\n10\n91\n12\n1001\nApp\n1000\nkeep\n";
        const auto wideFillet=Drafting::fillet(wide,1,2);
        const auto wp=readLWPolyline(wideFillet);
        check(std::abs(wp.vertices()[0].endWidth-3.6)<1e-12 && std::abs(wp.vertices()[1].startWidth-3.6)<1e-12 && std::abs(wp.vertices()[1].endWidth-6.4)<1e-12);
        check(wideFillet.find("91\n11\n")!=std::string::npos && wideFillet.find("1000\nkeep\n")!=std::string::npos);
        const auto bevel=readLWPolyline(Drafting::chamfer(elbow,1,2,3));
        check(bevel.vertices().size()==4 && bevel.vertices()[1].x==8 && bevel.vertices()[2].y==3 && bevel.vertices()[1].bulge==0);
        rejects([&] { Drafting::chamfer(elbow,1,0,2); });
        rejects([&] { Drafting::chamfer(elbow,1,2,20); });
        const auto closedBevel=readLWPolyline(Drafting::chamfer(rectangle,0,1,2));
        check(closedBevel.closed() && closedBevel.vertices().size()==5 && closedBevel.vertices()[0].y==1 && closedBevel.vertices()[1].x==2);
        const auto text=Drafting::createText("Original",2,{1,2,3});
        const auto textEdit=Drafting::editText(text,"Updated",3);
        check(Drafting::textInfo(textEdit).text=="Updated" && Drafting::textInfo(textEdit).height==3);
        const std::string paragraphs="First\nSecond {literal} \\P";
        const auto multiline=Drafting::createText(paragraphs,2,{1,2,3},true,20);
        check(Drafting::textInfo(multiline).text==paragraphs && Drafting::textInfo(multiline).referenceWidth==20);
        const std::string longText(700,'x');
        const auto longMtext=Drafting::createText(longText,2,{0,0,0},true,0);
        check(Drafting::textInfo(longMtext).text==longText && parseEntity(longMtext)->record().value(3).size()==250);
        rejects([&] { Drafting::createText(longText,2,{0,0,0}); });
        rejects([&] { Drafting::editText(text,"",2); });
        rejects([&] { Drafting::editText(text,"Line\nTwo",2); });
        rejects([&] { Drafting::editText(text,"Bad",0); });
        const auto richText=text+"102\n{APP\n1\nKeep app text\n102\n}\n1001\nApp\n1000\nKeep xdata\n";
        const auto richEdit=Drafting::editText(richText,"New",4);
        check(richEdit.find("1\nKeep app text\n")!=std::string::npos && richEdit.find("1000\nKeep xdata\n")!=std::string::npos);
        std::string unicode;
        for (int j=0; j<200; ++j) unicode+="\xc3\xa9";
        const auto unicodeMtext=Drafting::createText(unicode,2,{0,0,0},true,0);
        check(Drafting::textInfo(unicodeMtext).text==unicode);
        const auto unicodeEntity=parseEntity(unicodeMtext);
        for (const auto& g : unicodeEntity->record().groups) if (g.first==1 || g.first==3) check(g.second.size()<=250);
        const auto newLayer=Drafting::setLayer(DXFDocument::empty(4).serialize(),"Walls",1,true);
        const auto layerDoc=DXFDocument::parse(newLayer);
        check(layerDoc.layers.at("Walls").color==1 && layerDoc.layers.at("Walls").visible && layerDoc.layers.count("0"));
        const auto layerOff=DXFDocument::parse(Drafting::setLayer(newLayer,"Walls",3,false));
        check(layerOff.layers.at("Walls").color==3 && !layerOff.layers.at("Walls").visible);
        const auto styled=parseEntity(Drafting::properties(line,"Walls",256,false));
        check(styled->layer()=="Walls" && !entityVisible(*styled));
        check(styled->geometry().segments[0].end.x==10);
        check(styled->raw().find("60\n1\n")<styled->raw().find("100\nAcDbLine\n"));
        const auto trueColor=line+"420\n16711680\n";
        check(parseEntity(Drafting::properties(trueColor,"0",-1,true))->record().number(420)==16711680);
        check(parseEntity(Drafting::properties(trueColor,"0",3,true))->record().value(420).empty());
        rejects([&] { Drafting::properties(line,"Walls",257,true); });
        rejects([&] { Drafting::setLayer(newLayer,"walls",2,true); });
        rejects([&] { Drafting::setLayer(newLayer,"Bad\nName",2,true); });
        rejects([&] { Drafting::setLayer(newLayer,"Bad|Name",2,true); });
        const auto minimal=std::string("0\nSECTION\n2\nENTITIES\n")+rich+"0\nENDSEC\n0\nEOF\n";
        const auto addedTable=DXFDocument::parse(Drafting::setLayer(minimal,"New.Layer",4,true));
        check(addedTable.layers.count("0") && addedTable.layers.count("New.Layer") && addedTable.entities[0]->handle()=="AB");
        const auto twoLayers=Drafting::setLayer(newLayer,"Doors",2,true);
        const auto allGroups=readDXFGroups(twoLayers);
        std::set<std::string> usedHandles;
        for (const auto& g : allGroups.groups) if (g.first==5) check(usedHandles.insert(g.second).second);
        const auto roundtrip=DXFDocument::parse(DXFDocument::parse(twoLayers).serialize({}, {}, {parseEntity(Drafting::properties(createCircle({0,0,0},1),"Doors",256,true))->raw()}));
        check(roundtrip.entities.size()==1 && roundtrip.layers.at("Doors").color==2);
        std::cout<<"Native LINE trim/extend, boundary restrictions and record preservation passed.\n";
    } catch (const std::exception& e) { std::cerr<<e.what()<<'\n'; return 1; }
}
